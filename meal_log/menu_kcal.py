_COMPILED = tuple((re.compile(p, re.IGNORECASE), m) for p, m in STORE_RULES)


def guess_menu(store_name: str) -> Optional[str]:
    """가게 이름 → 메뉴 (기준표에 있는 이름). 못 정하면 None (메뉴 모름)."""
    for pat, menu in _COMPILED:
        if pat.search(store_name or ""):
            return menu
    return None


def check_table() -> list[str]:
    """규칙이 가리키는 메뉴가 기준표에 다 있는지, 범위가 낮음 ≤ 보통 ≤ 높음인지 (테스트에서 부름)."""
    errs = [f"규칙의 메뉴가 기준표에 없음: {m}" for _, m in STORE_RULES if m not in MENUS]
    errs += [f"DB 값의 메뉴가 기준표에 없음: {n}" for n in DB_VALUES if n not in MENUS]
    errs += [f"범위가 이상함: {k.name}" for k in MENUS.values() if not (0 <= k.low <= k.mid <= k.high)]
    return errs
